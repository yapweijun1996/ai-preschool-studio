/// <reference types="vitest/config" />
import { defineConfig, type Plugin } from 'vite';
import react from '@vitejs/plugin-react';
import { listFiles, readSwTemplate, resolveBuildId, resolveVersion } from './scripts/build-info.mjs';

// Release identity: package.json version + short git SHA (env APP_VERSION / BUILD_ID override).
const version = resolveVersion();
const build = resolveBuildId();

/**
 * Writes sw.js (VERSION, BUILD and the precache list embedded, so its bytes change every
 * release) and version.json next to index.html. Build only: dev never gets a service worker.
 */
function pwaRelease(): Plugin {
  let publicDir = '';
  return {
    name: 'aps-pwa-release',
    apply: 'build',
    enforce: 'post',
    configResolved(config) {
      publicDir = config.publicDir;
    },
    generateBundle(_options, bundle) {
      const skip = new Set(['sw.js', 'version.json']);
      // index.html is listed explicitly in case Vite's HTML asset is emitted after this hook.
      const files = new Set(['index.html', ...Object.keys(bundle), ...listFiles(publicDir)]);
      const precache = [...files].filter((f) => !skip.has(f) && !f.endsWith('.map')).sort();
      const header =
        `// Generated by vite.config.ts (aps-pwa-release). Do not edit.\n` +
        `const VERSION = ${JSON.stringify(version)};\n` +
        `const BUILD = ${JSON.stringify(build)};\n` +
        `const PRECACHE = ${JSON.stringify(precache, null, 2)};\n`;
      this.emitFile({ type: 'asset', fileName: 'sw.js', source: header + readSwTemplate() });
      this.emitFile({
        type: 'asset',
        fileName: 'version.json',
        source: JSON.stringify({ version, build, builtAt: new Date().toISOString() }, null, 2) + '\n'
      });
    }
  };
}

// Relative base so the static build works from any sub-path (e.g. GitHub Pages).
export default defineConfig({
  base: './',
  plugins: [react(), pwaRelease()],
  define: {
    'import.meta.env.VITE_APP_VERSION': JSON.stringify(version),
    'import.meta.env.VITE_BUILD_ID': JSON.stringify(build)
  },
  test: {
    environment: 'jsdom',
    include: ['tests/**/*.test.{ts,tsx}']
  }
});
